"""Start states, reset and training aid of the stand-up task."""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from typing import TYPE_CHECKING

import numpy as np
import torch
from mjlab.entity import Entity
from mjlab.managers.scene_entity_config import SceneEntityCfg
from mjlab.utils.lab_api.math import (
  quat_from_angle_axis,
  quat_from_euler_xyz,
  quat_mul,
  sample_uniform,
)
from mjlab.utils.lab_api.string import resolve_matching_names_values
from scipy.spatial import ConvexHull

from .contacts import StandCfg, get_ground_contact, height_progress, torso_body_id

if TYPE_CHECKING:
  from mjlab.envs import ManagerBasedRlEnv

_LIBRARY_ATTR = "_stand_up_start_states"
_START_ACTION_ATTR = "_stand_up_start_action"


@dataclass
class StartStateCfg:
  """How the library of resting start states is generated.

  Robots are dropped from just above the ground while their joints are driven
  to random targets, or lowered into a squat, and are kept if they are at
  rest once the time is up.
  """

  num_states: int = 8192
  """States to generate at least, ``num_envs`` at a time."""
  crouch_fraction: float = 0.3
  """Share of robots that are lowered into a squat instead of dropped."""
  crouch_leg_length_range: tuple[float, float] = (0.0, 0.0)
  """Leg length target [m] of a squat."""
  crouch_leg_length_difference: float = 0.03
  crouch_joint_offset: dict[str, tuple[float, float]] = field(default_factory=dict)
  """Joint name regex -> offset range [rad] from the default pose in a squat."""
  leg_length_joint_regex: str = ""
  upright_fraction: float = 0.2
  """Share of drops that start within ``upright_max_tilt`` of upright; the
  others start in a uniformly random orientation."""
  upright_max_tilt: float = math.radians(40.0)
  default_pose_fraction: float = 0.15
  """Share of drops that keep the default joint pose."""
  joint_hulls: tuple[tuple[tuple[str, str], torch.Tensor], ...] = ()
  """Joint pairs whose targets and resting positions must lie inside a convex
  hull."""
  drop_clearance: float = 0.02
  ramp_time_s: float = 1.0
  """Time over which the joint targets move to the random ones."""
  settle_time_s: float = 2.0
  relaxed_fraction: float = 0.5
  """Share of drops whose actuators only damp the motion while settling."""
  max_joint_speed: float = 0.5
  max_root_speed: float = 0.2
  """Speeds below which a robot counts as at rest."""
  entity_name: str = "robot"


class StartStateLibrary:
  """Resting states of the robot, generated by simulation."""

  def __init__(self, env: ManagerBasedRlEnv, cfg: StartStateCfg):
    self.cfg = cfg
    asset: Entity = env.scene[cfg.entity_name]
    self._asset = asset
    device = env.device

    joint_ids, _ = asset.find_joints_by_actuator_names((".*",))
    self._act_ids = torch.as_tensor(joint_ids, device=device, dtype=torch.long)

    # Collision geoms of the robot, for the drop height.
    model = env.sim.mj_model
    geom_ids = asset.indexing.geom_ids.cpu().numpy()
    collides = (model.geom_contype[geom_ids] != 0) | (
      model.geom_conaffinity[geom_ids] != 0
    )
    self._geom_ids = torch.as_tensor(geom_ids[collides], device=device).long()
    self._geom_rbound = torch.as_tensor(
      model.geom_rbound[geom_ids[collides]], dtype=torch.float32, device=device
    )

    names = [asset.joint_names[i] for i in joint_ids]
    self._hulls = []
    for (regex_1, regex_2), points in cfg.joint_hulls:
      first = asset.find_joints((regex_1,), joint_subset=names)[0]
      second = asset.find_joints((regex_2,), joint_subset=names)[0]
      equations = ConvexHull(np.asarray(points.cpu())).equations
      normals = torch.as_tensor(equations[:, :-1], dtype=torch.float32, device=device)
      offsets = torch.as_tensor(equations[:, -1], dtype=torch.float32, device=device)
      self._hulls.append((first, second, normals, offsets))

    self._leg_length_ids: list[int] = []
    self._crouch_offset = torch.zeros(len(names), 2, device=device)
    if cfg.crouch_fraction > 0.0:
      self._leg_length_ids = asset.find_joints(
        (cfg.leg_length_joint_regex,), joint_subset=names
      )[0]
      index, _, offset = resolve_matching_names_values(cfg.crouch_joint_offset, names)
      self._crouch_offset[index] = torch.tensor(offset, device=device)

    rounds = max(1, math.ceil(cfg.num_states / env.num_envs))
    states = [self._generate(env) for _ in range(rounds)]
    self.root_height = torch.cat([s[0] for s in states])
    self.root_quat = torch.cat([s[1] for s in states])
    self.joint_pos = torch.cat([s[2] for s in states])
    if len(self.root_height) == 0:
      raise RuntimeError("No start state could be generated: no robot came to rest.")

  def __len__(self) -> int:
    return len(self.root_height)

  def _pull_inside_hulls(self, target: torch.Tensor) -> torch.Tensor:
    """[n, actuated joints] with every hull pair pulled towards the origin
    until it is inside its hull."""
    target = target.clone()
    for first, second, normals, offsets in self._hulls:
      for id_1, id_2 in zip(first, second, strict=True):
        point = torch.stack([target[:, id_1], target[:, id_2]], dim=-1)
        # Inside the hull: normals @ p + offsets <= 0.
        along = point @ normals.T
        scale = torch.where(
          along > 0, -offsets / along.clamp(min=1e-9), torch.ones_like(along)
        )
        scale = scale.min(dim=-1).values.clamp(max=1.0)
        target[:, id_1] = point[:, 0] * scale
        target[:, id_2] = point[:, 1] * scale
    return target

  def _inside_hulls(self, joint_pos: torch.Tensor) -> torch.Tensor:
    """[n] whether every hull pair of ``joint_pos`` [n, actuated joints] is
    inside its hull."""
    inside = torch.ones(len(joint_pos), dtype=torch.bool, device=joint_pos.device)
    for first, second, normals, offsets in self._hulls:
      for id_1, id_2 in zip(first, second, strict=True):
        point = torch.stack([joint_pos[:, id_1], joint_pos[:, id_2]], dim=-1)
        inside &= (point @ normals.T + offsets <= 0.0).all(dim=-1)
    return inside

  def _sample_joint_targets(self, n: int, device: str) -> torch.Tensor:
    """Random targets within the soft limits and the hulls."""
    asset = self._asset
    limits = asset.data.soft_joint_pos_limits[:n][:, self._act_ids]
    middle = 0.5 * (limits[..., 0] + limits[..., 1])
    half = 0.5 * (limits[..., 1] - limits[..., 0])
    target = middle + half * sample_uniform(-1.0, 1.0, middle.shape, device)
    target = self._pull_inside_hulls(target)
    default = asset.data.default_joint_pos[:n][:, self._act_ids]
    keep_default = torch.rand(n, device=device) < self.cfg.default_pose_fraction
    return torch.where(keep_default.unsqueeze(-1), default, target)

  def _sample_crouch_targets(self, n: int, device: str) -> torch.Tensor:
    """Targets of a squat: the default pose with an offset and shortened legs."""
    cfg = self.cfg
    asset = self._asset
    default = asset.data.default_joint_pos[:n][:, self._act_ids]
    low, high = self._crouch_offset[:, 0], self._crouch_offset[:, 1]
    target = default + low + (high - low) * torch.rand(default.shape, device=device)
    length = sample_uniform(*cfg.crouch_leg_length_range, (n, 1), device)
    difference = sample_uniform(
      -0.5 * cfg.crouch_leg_length_difference,
      0.5 * cfg.crouch_leg_length_difference,
      (n, len(self._leg_length_ids)),
      device,
    )
    target[:, self._leg_length_ids] = length + difference
    limits = asset.data.soft_joint_pos_limits[:n][:, self._act_ids]
    return self._pull_inside_hulls(target.clamp(limits[..., 0], limits[..., 1]))

  def _generate(
    self, env: ManagerBasedRlEnv
  ) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
    """Drop every robot once and return the states of those that came to rest."""
    cfg = self.cfg
    asset = self._asset
    n, device = env.num_envs, env.device
    origins = env.scene.env_origins

    # Orientation: upright for a squat, near upright or random for a drop.
    random_quat = torch.nn.functional.normalize(
      torch.randn(n, 4, device=device), dim=-1
    )
    yaw = sample_uniform(-math.pi, math.pi, (n,), device)
    heading = sample_uniform(-math.pi, math.pi, (n,), device)
    zeros = torch.zeros_like(yaw)
    tilt_axis = torch.stack([torch.cos(heading), torch.sin(heading), zeros], dim=-1)
    tilt = sample_uniform(0.0, cfg.upright_max_tilt, (n,), device)
    upright_quat = quat_mul(
      quat_from_angle_axis(tilt, tilt_axis), quat_from_euler_xyz(zeros, zeros, yaw)
    )
    kind = torch.rand(n, device=device)
    crouch = kind < cfg.crouch_fraction
    upright = ~crouch & (kind < cfg.crouch_fraction + cfg.upright_fraction)
    quat = torch.where(upright.unsqueeze(-1), upright_quat, random_quat)
    quat = torch.where(
      crouch.unsqueeze(-1), quat_from_euler_xyz(zeros, zeros, yaw), quat
    )

    # Default joint pose, lowered until just above the ground.
    joint_pos = asset.data.default_joint_pos.clone()
    joint_vel = torch.zeros_like(joint_pos)
    position = origins.clone()
    position[:, 2] += 3.0
    asset.write_root_link_pose_to_sim(torch.cat([position, quat], dim=-1))
    asset.write_root_link_velocity_to_sim(torch.zeros(n, 6, device=device))
    asset.write_joint_state_to_sim(joint_pos, joint_vel)
    env.sim.forward()
    lowest = (
      (env.sim.data.geom_xpos[:, self._geom_ids, 2] - self._geom_rbound)
      .min(dim=-1)
      .values
    )
    position[:, 2] -= lowest - origins[:, 2] - cfg.drop_clearance
    asset.write_root_link_pose_to_sim(torch.cat([position, quat], dim=-1))

    # Fall, land and settle.
    default = joint_pos[:, self._act_ids]
    goal = self._sample_joint_targets(n, device)
    relaxed = torch.rand(n, device=device) < cfg.relaxed_fraction
    if cfg.crouch_fraction > 0.0:
      goal = torch.where(
        crouch.unsqueeze(-1), self._sample_crouch_targets(n, device), goal
      )
      relaxed &= ~crouch  # A squat is held.
    relaxed = relaxed.unsqueeze(-1)
    ramp_steps = max(1, round(cfg.ramp_time_s / env.step_dt))
    settle_steps = max(1, round(cfg.settle_time_s / env.step_dt))
    for step in range(ramp_steps + settle_steps):
      blend = min(1.0, (step + 1) / ramp_steps)
      target = default + blend * (goal - default)
      if step >= ramp_steps:
        current = asset.data.joint_pos[:, self._act_ids]
        target = torch.where(relaxed, current, target)
      asset.set_joint_position_target(target, joint_ids=self._act_ids)
      for _ in range(env.cfg.decimation):
        env.scene.write_data_to_sim()
        env.sim.step()
        env.scene.update(dt=env.physics_dt)
    env.sim.forward()

    # Keep the robots that are at rest.
    root_quat = asset.data.root_link_quat_w.clone()
    height = (asset.data.root_link_pos_w[:, 2] - origins[:, 2]).clone()
    joint_pos = asset.data.joint_pos.clone()
    joint_speed = asset.data.joint_vel.abs().max(dim=-1).values
    root_speed = torch.linalg.vector_norm(asset.data.root_link_lin_vel_w, dim=-1)
    valid = (
      torch.isfinite(joint_pos).all(dim=-1)
      & torch.isfinite(root_quat).all(dim=-1)
      & (joint_speed < cfg.max_joint_speed)
      & (root_speed < cfg.max_root_speed)
      & (height > 0.0)
      # Contacts can push a joint pair out of reach of the real transmission.
      & self._inside_hulls(joint_pos[:, self._act_ids])
    )
    return height[valid], root_quat[valid], joint_pos[valid]


def get_start_state_library(
  env: ManagerBasedRlEnv, cfg: StartStateCfg
) -> StartStateLibrary:
  """The environment's start state library, generated on first use."""
  library: StartStateLibrary | None = getattr(env, _LIBRARY_ATTR, None)
  if library is None:
    library = StartStateLibrary(env, cfg)
    setattr(env, _LIBRARY_ATTR, library)
  return library


def generate_start_states(
  env: ManagerBasedRlEnv, env_ids: torch.Tensor | None, start_cfg: StartStateCfg
) -> None:
  """Generate the start states. For ``mode="startup"``, after the domain
  randomization terms."""
  del env_ids
  get_start_state_library(env, start_cfg)


def get_start_action(env: ManagerBasedRlEnv) -> torch.Tensor:
  """[B, action_dim] the action that holds each robot in its start pose.

  It stands in for the previous action in the first step of an episode, in
  the observations and in the action smoothness rewards.
  """
  action: torch.Tensor | None = getattr(env, _START_ACTION_ATTR, None)
  if action is None:
    action = torch.zeros(
      env.num_envs, env.action_manager.total_action_dim, device=env.device
    )
    setattr(env, _START_ACTION_ATTR, action)
  return action


def reset_to_start_state(
  env: ManagerBasedRlEnv,
  env_ids: torch.Tensor | None,
  start_cfg: StartStateCfg,
  standing_fraction: float = 0.1,
  position_range: tuple[float, float] = (-0.5, 0.5),
  standing_height_range: tuple[float, float] = (0.006, 0.015),
  standing_joint_pos_noise: float = 0.05,
  fallen_clearance: float = 0.002,
  action_name: str = "joint_pos",
  asset_cfg: SceneEntityCfg | None = None,
) -> None:
  """Reset to a state at rest, turned to a random heading.

  A ``standing_fraction`` of the episodes starts in the default pose with an
  offset on ``asset_cfg``'s joints, the others from the start state library.
  """
  if env_ids is None:
    env_ids = torch.arange(env.num_envs, device=env.device)
  n, device = len(env_ids), env.device
  asset: Entity = env.scene[start_cfg.entity_name]
  library = get_start_state_library(env, start_cfg)

  # Standing: the default state with a joint offset.
  default_root = asset.data.default_root_state[env_ids]
  standing_height = default_root[:, 2] + sample_uniform(
    *standing_height_range, (n,), device
  )
  standing_joint_pos = asset.data.default_joint_pos[env_ids].clone()
  if standing_joint_pos_noise > 0.0 and asset_cfg is not None:
    joint_ids = asset_cfg.joint_ids
    shape = standing_joint_pos[:, joint_ids].shape
    noisy = standing_joint_pos[:, joint_ids] + sample_uniform(
      -standing_joint_pos_noise, standing_joint_pos_noise, shape, device
    )
    limits = asset.data.soft_joint_pos_limits[env_ids][:, joint_ids]
    standing_joint_pos[:, joint_ids] = noisy.clamp(limits[..., 0], limits[..., 1])

  # Fallen: a resting state from the library.
  index = torch.randint(0, len(library), (n,), device=device)
  standing = torch.rand(n, device=device) < standing_fraction
  height = torch.where(
    standing, standing_height, library.root_height[index] + fallen_clearance
  )
  quat = torch.where(
    standing.unsqueeze(-1), default_root[:, 3:7], library.root_quat[index]
  )
  joint_pos = torch.where(
    standing.unsqueeze(-1), standing_joint_pos, library.joint_pos[index]
  )

  yaw = sample_uniform(-math.pi, math.pi, (n,), device)
  zeros = torch.zeros_like(yaw)
  quat = quat_mul(quat_from_euler_xyz(zeros, zeros, yaw), quat)
  position = env.scene.env_origins[env_ids].clone()
  position[:, 0:2] += sample_uniform(*position_range, (n, 2), device)
  position[:, 2] += height

  asset.write_root_link_pose_to_sim(
    torch.cat([position, quat], dim=-1), env_ids=env_ids
  )
  asset.write_root_link_velocity_to_sim(
    torch.zeros(n, 6, device=device), env_ids=env_ids
  )
  asset.write_joint_state_to_sim(
    joint_pos, torch.zeros_like(joint_pos), env_ids=env_ids
  )

  # The action whose joint targets are the measured joint positions.
  term = env.action_manager.get_term(action_name)
  measured = joint_pos + asset.data.encoder_bias[env_ids]
  scale, offset = term.scale, term.offset
  if isinstance(scale, torch.Tensor):
    scale = scale[env_ids]
  if isinstance(offset, torch.Tensor):
    offset = offset[env_ids]
  get_start_action(env)[env_ids] = (measured[:, term.target_ids] - offset) / scale


def lift_assist(
  env: ManagerBasedRlEnv,
  env_ids: torch.Tensor | None,
  stand_cfg: StandCfg,
  level: float = 0.0,
) -> None:
  """Carry part of the robot's weight while it is down. A training aid.

  For ``mode="step"``. An upward force on the torso of ``level`` robot weights
  while the base is on the ground, falling to nothing at standing height.
  """
  del env_ids
  asset: Entity = env.scene[stand_cfg.entity_name]
  weight = get_ground_contact(env, stand_cfg.contact_cfg).weight
  force = torch.zeros(env.num_envs, 1, 3, device=env.device)
  force[:, 0, 2] = level * weight * (1.0 - height_progress(env, stand_cfg))
  asset.write_external_wrench_to_sim(
    force,
    torch.zeros_like(force),
    body_ids=[torso_body_id(env, asset, stand_cfg.torso_body)],
  )
