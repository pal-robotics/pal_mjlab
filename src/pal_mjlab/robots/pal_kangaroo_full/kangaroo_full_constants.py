def _name_geoms(spec: mujoco.MjSpec) -> None:
  """Name the generator's anonymous geoms, so regexes can select them.

  ``_replace_collisions`` runs first and names every capsule it adds, so this
  covers the ~90 visual meshes left over. mjlab's ``CollisionCfg`` looks geoms up
  by name and disables every geom it does not match, so leaving them anonymous
  makes that lookup collapse onto a single empty name.
  """
  for body in spec.bodies:
    counts: dict[str, int] = {}
    for geom in body.geoms:
      if geom.name:
        continue
      kind = "collision" if geom.group == _COLLISION_GROUP else "visual"
      index = counts.get(kind, 0)
      counts[kind] = index + 1
      geom.name = f"{body.name}_{kind}" + (f"_{index}" if index else "")


