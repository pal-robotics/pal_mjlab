def _style_visuals(spec: mujoco.MjSpec) -> None:
  """Register the two materials the copied XML lacks, and fix up the visuals.

  Visual geoms must not contribute mass. That is not cosmetic: ``torso_imu_link``
  is the one body the generator leaves without an ``<inertial>``, so its 5 mm
  marker box would otherwise weigh a gram at the default density of 1000.

  Applied per geom rather than to the ``visual`` default class, because MjSpec
  resolves classes onto elements at parse time -- editing the class after loading
  would only reach geoms added later, of which there are none.
  """
  existing = {material.name for material in spec.materials}
  if _VISUAL_MATERIAL not in existing:
    spec.add_material(name=_VISUAL_MATERIAL, rgba=[0.298039, 0.298039, 0.298039, 1.0])
  if _COLLISION_MATERIAL not in existing:
    spec.add_material(name=_COLLISION_MATERIAL, rgba=[1.0, 0.65, 0.0, 0.2])

  for body in spec.bodies:
    for geom in body.geoms:
      if geom.classname is None or geom.classname.name != _VISUAL_CLASS:
        continue
      geom.density = 0.0
      if not geom.material:  # the meshes carry their own; the marker box does not
        geom.material = _VISUAL_MATERIAL


def _require_body(spec: mujoco.MjSpec, name: str, wanted_by: str) -> mujoco.MjsBody:
  body = spec.body(name)
  if body is None:
    raise ValueError(
      f"{KANG_FULL_XML.name} has no body '{name}' to hang '{wanted_by}' off; "
      "body names last changed in the 2026-08 regeneration."
    )
  return body


def _replace_collisions(spec: mujoco.MjSpec) -> None:
  """Swap the converter's per-mesh collision twins for ``_CAPSULES``.

  The capsules are given ``density=0``: the bodies they hang off all declare an
  explicit ``<inertial>``, so geom-derived mass is ignored anyway, and a
  collision proxy has no business changing the robot's dynamics if that ever
  stops being true.

  ``FULL_COLLISION`` selects contact geoms by the ``.*_collision`` suffix, and
  ``_name_geoms`` hands that same suffix to any unnamed group-3 geom, so this
  ends by checking the collision group holds exactly the capsules -- a
  regenerated MJCF that grows a collision geom we did not put there fails loudly
  rather than quietly adding contact geometry to training.
  """
  generated = [
    geom
    for body in spec.bodies
    for geom in body.geoms
    if geom.classname is not None and geom.classname.name == _COLLISION_CLASS
  ]
  if not generated:
    raise ValueError(
      f"{KANG_FULL_XML.name} has no '{_COLLISION_CLASS}'-class geoms; the "
      "converter used to clone one per visual mesh -- check what it emits now "
      "before assuming the capsules below are the whole collision model."
    )
  for geom in generated:
    spec.delete(geom)

  for frame in _FRAMES:
    _require_body(spec, frame.parent, frame.name).add_body(
      name=frame.name, pos=frame.pos, quat=frame.quat
    )

  for capsule in _CAPSULES:
    body = _require_body(spec, capsule.body, capsule.name)
    shape = (
      {"fromto": capsule.fromto, "size": [capsule.radius, 0.0, 0.0]}
      if capsule.fromto is not None
      else {
        "pos": capsule.pos,
        "quat": capsule.quat,
        "size": [capsule.radius, capsule.half_length, 0.0],
      }
    )
    body.add_geom(
      name=capsule.name,
      type=mujoco.mjtGeom.mjGEOM_CAPSULE,
      group=_COLLISION_GROUP,
      contype=1,
      conaffinity=1,
      density=0.0,
      material=_COLLISION_MATERIAL,
      **shape,
    )

  in_group = {
    geom.name
    for body in spec.bodies
    for geom in body.geoms
    if geom.group == _COLLISION_GROUP
  }
  expected = {capsule.name for capsule in _CAPSULES}
  if in_group != expected:
    raise ValueError(
      "unexpected geoms in the collision group after replacement: "
      f"extra={sorted(in_group - expected)}, missing={sorted(expected - in_group)}"
    )


def _add_state_sensors(spec: mujoco.MjSpec) -> None:
  """Add the root-state sensors the velocity task observes.

  The generator emits only three IMU sensors (quat/gyro/accel), but the task's
  observations and mjlab's ``angular_momentum`` reward reference the set the
  previous hand-written model carried. The generated ``torso_imu_link`` site sits
  on ``pelvis_2_link`` at the same pose the old ``imu`` site did, so these read
  identically to before.

  Names and types match pal_kangaroo's hand-written model exactly, so the two
  robots can share observation configs -- and mjlab's own defaults, which ask for
  ``robot/imu_ang_vel`` and ``robot/imu_lin_vel``, resolve without an override.

  ``imu_ang_vel`` is a GYRO, i.e. angular velocity in the *site's* frame. That is
  what a real IMU reports; a FRAMEANGVEL would be world-frame and could not be
  fed from hardware without first estimating the base orientation.
  """
  existing = {sensor.name for sensor in spec.sensors}
  site = _IMU_SITE
  specs: tuple[tuple[str, mujoco.mjtSensor, mujoco.mjtObj, str], ...] = (
    ("imu_quat", mujoco.mjtSensor.mjSENS_FRAMEQUAT, mujoco.mjtObj.mjOBJ_SITE, site),
    ("imu_ang_vel", mujoco.mjtSensor.mjSENS_GYRO, mujoco.mjtObj.mjOBJ_SITE, site),
    (
      "imu_lin_vel",
      mujoco.mjtSensor.mjSENS_VELOCIMETER,
      mujoco.mjtObj.mjOBJ_SITE,
      site,
    ),
    (
      "imu_lin_acc",
      mujoco.mjtSensor.mjSENS_ACCELEROMETER,
      mujoco.mjtObj.mjOBJ_SITE,
      site,
    ),
    (
      "root_angmom",
      mujoco.mjtSensor.mjSENS_SUBTREEANGMOM,
      mujoco.mjtObj.mjOBJ_BODY,
      _ROOT_BODY,
    ),
  )
  for name, sensor_type, objtype, objname in specs:
    if name in existing:
      continue
    spec.add_sensor(name=name, type=sensor_type, objtype=objtype, objname=objname)


def _normalize_spec(spec: mujoco.MjSpec) -> mujoco.MjSpec:
  # Drop the XML's <motor> actuators; mjlab adds <position> actuators of its own
  # from KANG_FULL_ARTICULATION and does not remove pre-existing ones.
  for actuator in list(spec.actuators):
    spec.delete(actuator)

  # Drop the standalone viewer scene, which would duplicate mjlab's terrain.
  for geom in list(spec.worldbody.geoms):
    if geom.name in _SCENE_GEOMS:
      spec.delete(geom)
  for material in list(spec.materials):
    if material.name in _SCENE_MATERIALS:
      spec.delete(material)
  for texture in list(spec.textures):
    if texture.name in _SCENE_TEXTURES:
      spec.delete(texture)

  _style_visuals(spec)
  _replace_collisions(spec)
  _name_geoms(spec)
  _add_state_sensors(spec)
  return spec


def _load_spec(xml_path: Path) -> mujoco.MjSpec:
  return _normalize_spec(mujoco.MjSpec.from_file(str(xml_path)))


def get_kangaroo_spec() -> mujoco.MjSpec:
  return _load_spec(KANG_FULL_XML)


