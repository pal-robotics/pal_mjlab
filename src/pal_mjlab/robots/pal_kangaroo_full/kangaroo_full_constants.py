class _Frame(NamedTuple):
  """A massless carrier body the sole and ankle capsules hang off."""

  name: str
  parent: str
  pos: tuple[float, float, float] = (0.0, 0.0, 0.0)
  quat: tuple[float, float, float, float] = (1.0, 0.0, 0.0, 0.0)


class _Capsule(NamedTuple):
  """One collision capsule, in the local frame of ``body``.

  Given either by its two endpoints (``fromto``) or, for the capsules that came
  out of a mesh-fitting tool, by ``pos``/``quat``/``half_length``.
  """

  body: str
  name: str
  radius: float
  fromto: tuple[float, ...] | None = None
  pos: tuple[float, float, float] | None = None
  quat: tuple[float, float, float, float] | None = None
  half_length: float | None = None


def _leg_frames(side: str) -> tuple[_Frame, ...]:
  """The two carrier bodies pal_kangaroo hangs each foot's capsules off.

  These look removable -- they hold no joint, so they are welded to
  ``leg_*_5_link`` and can neither move nor collide independently -- but they are
  not. MuJoCo derives each contact's regularization from ``body_invweight0`` of
  the body owning the geom, and that is measured at the body's *own* origin:
  0.841 at ``leg_*_foot_link`` against 0.630 one body up. Re-expressing the
  capsules in ``leg_*_5_link`` reproduced every compiled geom pose to 1e-17 and
  still stiffened the foot contacts by 25%, so the frames are rebuilt here.
  """
  return (
    _Frame(
      f"leg_{side}_foot_link",
      f"leg_{side}_5_link",
      pos=(0.0, 0.0, -0.034),
      quat=(0.9848078, 0.0, -0.1736482, 0.0),
    ),
    _Frame(f"leg_{side}_ankle_link", f"leg_{side}_foot_link"),
  )


_FRAMES: tuple[_Frame, ...] = (*_leg_frames("left"), *_leg_frames("right"))


