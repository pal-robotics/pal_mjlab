# Collision geometry.
#
# The generated MJCF carries no collision model of its own: the converter clones
# every visual mesh into a `collision` twin (90 of them), which is both far too
# expensive to simulate and far too detailed to be useful. Those are dropped on
# load and replaced by the capsule set below.
#
# 25 of the 27 capsules are lifted verbatim from the hand-written pal_kangaroo
# model (``robots/pal_kangaroo/xmls/kangaroo.xml``), so both robots present the
# same contact geometry to a policy. The two hip-xy motor capsules have no
# counterpart there: the simple model folds away the leg linkage that carries
# those bodies.
##

